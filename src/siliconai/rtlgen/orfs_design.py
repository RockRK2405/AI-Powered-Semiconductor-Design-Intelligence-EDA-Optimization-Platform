"""Write a generated design as an ORFS design directory (config.mk + SDC + RTL).

The directory is bind-mounted read-only into the ORFS container at
``flow/designs/<platform>/<name>`` (see ``eda/orfs.py``), so ORFS treats it exactly like a
bundled design. Names start with ``sai_`` so they can never shadow a bundled design.
"""

from __future__ import annotations

from pathlib import Path

from siliconai.rtlgen.generators import GeneratedDesign

# Platforms supported for generated designs, with platform-specific config lines.
# nangate45: small blocks need a finer power grid; we reuse the one ORFS ships for gcd.
# The other platforms' bundled gcd uses the platform's default power grid, so we do too.
PLATFORM_EXTRAS: dict[str, list[str]] = {
    "nangate45": [
        "export PDN_TCL ?= $(DESIGN_HOME)/nangate45/gcd/grid_strategy-M1-M4-M7.tcl",
    ],
    "asap7": [],
    "gf180": [],
    "ihp-sg13g2": [],
    "sky130hd": [],
}

# Generator clock periods were chosen for nangate45. On another platform they are scaled by
# the ratio of that platform's bundled gcd clock period to nangate45's (0.25 ns), so timing
# pressure stays comparable: asap7 310 ps, gf180 3 ns, ihp-sg13g2 1.5 ns, sky130hd 1.1 ns
# (ORFS image 620c13d9). Values are in each platform's SDC time unit (asap7: ps).
PERIOD_SCALE = {
    "nangate45": 1.0,
    "asap7": 0.31 / 0.25 * 1000.0,
    "gf180": 3.0 / 0.25,
    "ihp-sg13g2": 1.5 / 0.25,
    "sky130hd": 1.1 / 0.25,
}

SDC_TEMPLATE = """current_design {name}

set clk_name core_clock
set clk_port_name clk
set clk_period {period}
set clk_io_pct 0.2

set clk_port [get_ports $clk_port_name]

create_clock -name $clk_name -period $clk_period $clk_port
set clk_io_name vclk_$clk_name
create_clock -name $clk_io_name -period $clk_period

set non_clock_inputs [all_inputs -no_clocks]

set_input_delay [expr $clk_period * $clk_io_pct] -clock $clk_io_name $non_clock_inputs
set_output_delay [expr $clk_period * $clk_io_pct] -clock $clk_io_name [all_outputs]
"""


def design_config_path(platform: str, name: str) -> str:
    return f"./designs/{platform}/{name}/config.mk"


def write_orfs_design(design: GeneratedDesign, platform: str, root: Path) -> Path:
    """Materialize ``design`` under ``root/<platform>/<name>/``; returns that directory.

    Idempotent: the files are a pure function of (family, params, platform).
    """
    if platform not in PLATFORM_EXTRAS:
        raise ValueError(f"generated designs not supported on platform {platform!r}")
    out = Path(root) / platform / design.name
    out.mkdir(parents=True, exist_ok=True)
    base = f"$(DESIGN_HOME)/{platform}/{design.name}"
    config = [
        f"# Generated by siliconai.rtlgen ({design.family} {design.params})",
        f"export DESIGN_NAME = {design.name}",
        f"export DESIGN_NICKNAME = {design.name}",
        f"export PLATFORM = {platform}",
        f"export VERILOG_FILES = {base}/rtl.v",
        f"export SDC_FILE = {base}/constraint.sdc",
        "export CORE_UTILIZATION ?= 40",
        "export PLACE_DENSITY_LB_ADDON ?= 0.20",
        *PLATFORM_EXTRAS[platform],
    ]
    period = round(design.clock_period_ns * PERIOD_SCALE[platform], 6)
    files = {
        "rtl.v": design.verilog,
        "constraint.sdc": SDC_TEMPLATE.format(name=design.name, period=f"{period:g}"),
        "config.mk": "\n".join(config) + "\n",
    }
    for fname, text in files.items():
        path = out / fname
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
    return out
